def draw(item_id):
    shape, main, sec = ITEMS[item_id]
    rows = SHAPES[shape]
    k = {"O": P["outline"], "w": P["sun0"], "r": P["rune1"], "R": P["rune0"], "k": P["shade1"], " ": None}
    for i, c in enumerate(R[main]):
        k[str(i + 1)] = P[c]
    for i, c in enumerate(R[sec]):
        k["abcd"[i]] = P[c]
    if sec == "rune" and shape not in ("rune_stone", "map", "helm", "crown", "core"):
        pass
    # rune éteinte : les traits de rune restent gris
    if item_id == "eclat_de_rune_eteinte":
        k["r"], k["R"] = P["stone3"], P["stone2"]
    if item_id == "noyau_d_aube_intact":
        k["r"], k["R"] = P["sun1"], P["sun0"]
    rows = [r.replace("0", "O").replace(" ", "O") for r in rows]     # fautes de frappe -> contour
    h, w = len(rows), 16
    img = Image.new("RGBA", (16, 16), CLEAR)
    oy = (16 - h) // 2
    for y, row in enumerate(rows):
        for x, ch in enumerate(row[:w]):
            c = k.get(ch) if ch != "." else None
            if c:
                img.putpixel((x, y + oy), c)
    return img


def sheet(out):
    ids = sorted(ITEMS)
    cols, cell = 12, 24
    rows = (len(ids) + cols - 1) // cols
    im = Image.new("RGBA", (cols * cell, rows * cell), P["sun0"])
    bg = sb.from_ascii(["x"], {"x": P["earth0"]})
    for i, iid in enumerate(ids):
        x, y = (i % cols) * cell, (i // cols) * cell
        ImageDraw.Draw(im).rectangle([x + 1, y + 1, x + cell - 2, y + cell - 2], fill=P["earth0"])
        im.alpha_composite(draw(iid), (x + 4, y + 4))
    im.resize((im.width * 3, im.height * 3), Image.NEAREST).save(out)


