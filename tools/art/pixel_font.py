def rows_of(top, pattern):
    rows = pattern.split("/")
    w = max(len(r) for r in rows)
    grid = [[False] * w for _ in range(CELL_H)]
    for i, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == "#":
                grid[top + i][x] = True
    return grid, w


def compose(base, mark):
    top, pat = G[base]
    grid, w = rows_of(top, pat)
    m = (MARKS_UPPER if base.isupper() else MARKS_LOWER)[mark]
    row0 = 0 if base.isupper() else 1
    x0 = (w - len(m[0])) // 2
    for r, line in enumerate(m):
        for i, ch in enumerate(line):
            if ch == "#":
                grid[row0 + r][x0 + i] = True
    return grid, w


def main():
    glyphs = {}
    for ch, (top, pat) in G.items():
        glyphs[ch] = rows_of(top, pat)
    for ch, (top, pat) in SPECIAL.items():
        glyphs[ch] = rows_of(top, pat)
    for ch, (base, mark) in COMPOSE.items():
        glyphs[ch] = compose(base, mark)
    cols = 16
    cell_w = 8
    n = len(glyphs)
    img = Image.new("RGBA", (cols * cell_w, ((n + cols - 1) // cols) * CELL_H), (0, 0, 0, 0))
    px = img.load()
    meta = {"height": CELL_H, "ascent": 8, "descent": 2, "space": 3, "glyphs": {}}
    for i, (ch, (grid, w)) in enumerate(sorted(glyphs.items(), key=lambda kv: ord(kv[0]))):
        ox, oy = (i % cols) * cell_w, (i // cols) * CELL_H
        for y in range(CELL_H):
            for x in range(w):
                if grid[y][x]:
                    px[ox + x, oy + y] = (255, 255, 255, 255)
        meta["glyphs"][ch] = [ox, oy, w]
    out = ROOT / "assets" / "fonts"
    out.mkdir(parents=True, exist_ok=True)
    img.save(out / "arthesia_pixel.png")
    (out / "arthesia_pixel.json").write_text(json.dumps(meta, ensure_ascii=False), encoding="utf-8")
    # planche d'essai
    sample = ["Val-de-l'Aube · Mère Yvenne", "« Où est passée l'aube ? » — Ça, c'est étrange…",
              "ÉCHOPPE DE THESSALY : 15 or, 3 fioles (100%)", "àâäéèêëîïôöùûüç œ É È À Ç Ô Î"]
    sw = 320
    sh = len(sample) * 12 + 8
    sheet = Image.new("RGB", (sw, sh), (42, 26, 46))
    sp = sheet.load()
    for li, line in enumerate(sample):
        x = 4
        for ch in line:
            if ch == " " or ch == "—":
                x += meta["space"] + (3 if ch == "—" else 0)
                if ch == "—":
                    for k in range(5):
                        sp[x - 6 + k, 4 + li * 12 + 5] = (255, 244, 214)
                continue
            if ch not in glyphs:
                x += 4
                continue
            grid, w = glyphs[ch]
            for y in range(CELL_H):
                for gx in range(w):
                    if grid[y][gx] and x + gx < sw:
                        sp[x + gx, 4 + li * 12 + y] = (255, 244, 214)
            x += w + 1
    sheet.resize((sw * 3, sh * 3), Image.NEAREST).save(ROOT / "art" / "preview" / "police_pixel.png")
    print(f"OK - {n} glyphes")


if __name__ == "__main__":
    main()
